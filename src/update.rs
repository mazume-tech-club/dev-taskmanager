fn _path(_: &Path) {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn newer_comparison() {
        assert!(is_newer("0.2.0", "0.1.0"));
        assert!(is_newer("v1.0.0", "0.9.9"));
        assert!(!is_newer("0.1.0", "0.1.0"));
        assert!(!is_newer("0.0.9", "0.1.0"));
        assert!(!is_newer("garbage", "0.1.0"));
    }

    #[test]
    fn manifest_parses_tauri_format() {
        let text = r#"{"version":"1.2.3","notes":"n","pub_date":"2026-11-03T00:00:00Z",
            "platforms":{"windows-x86_64":{"signature":"c2ln","url":"https://x/y.exe"}}}"#;
        let m: Manifest = serde_json::from_str(text).unwrap();
        assert_eq!(m.version, "1.2.3");
        assert_eq!(m.platforms["windows-x86_64"].url, "https://x/y.exe");
    }

    #[test]
    fn verify_rejects_bad_signature() {
        let bad = base64::engine::general_purpose::STANDARD.encode("not a signature");
        assert!(verify(b"data", &bad).is_err());
        assert!(verify(b"data", "!!!").is_err());
    }

    #[test]
    fn embedded_public_key_is_valid() {
        assert!(minisign_verify::PublicKey::decode(PUBLIC_KEY.trim()).is_ok());
    }
}
