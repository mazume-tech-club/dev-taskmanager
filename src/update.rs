//! Auto-update: read `latest.json` from GitHub Releases (Tauri updater
//! format), download the new exe, verify its minisign signature, stage it,
//! and on request replace the running exe and restart.
//!
//! The resident process checks on a timer and stages silently; applying is
//! always a user action so monitoring and the log are not interrupted
//! unexpectedly.

use crate::config::{self, UpdateConfig};
use anyhow::{Context, Result, anyhow, bail};
use base64::Engine;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use std::time::Duration;

pub const DEFAULT_ENDPOINT: &str =
    "https://github.com/mazume-tech-club/dev-taskmanager/releases/latest/download/latest.json";
pub const CURRENT_VERSION: &str = env!("CARGO_PKG_VERSION");
/// minisign public key file text (two lines). Generated by `signer keygen`.
const PUBLIC_KEY: &str = include_str!("../assets/update-public-key.txt");
const MAX_DOWNLOAD: u64 = 200 * 1024 * 1024;
const PLATFORM: &str = "windows-x86_64";

#[derive(Debug, Clone, Deserialize)]
pub struct Manifest {
    pub version: String,
    #[serde(default)]
    pub notes: String,
    #[serde(default)]
    #[allow(dead_code)]
    pub pub_date: String,
    pub platforms: std::collections::HashMap<String, Platform>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct Platform {
    pub signature: String,
    pub url: String,
}

/// A downloaded and verified update waiting to be applied.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Staged {
    pub version: String,
    pub notes: String,
    pub path: PathBuf,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Outcome {
    UpToDate,
    Staged(Staged),
}

pub fn endpoint(cfg: &UpdateConfig) -> String {
    cfg.endpoint
        .clone()
        .filter(|s| !s.trim().is_empty())
        .unwrap_or_else(|| DEFAULT_ENDPOINT.to_string())
}

fn updates_dir() -> Result<PathBuf> {
    let dir = config::data_dir()?.join("updates");
    std::fs::create_dir_all(&dir)?;
    Ok(dir)
}

fn staged_path() -> Result<PathBuf> {
    Ok(updates_dir()?.join("staged.json"))
}

fn agent() -> ureq::Agent {
    let config = ureq::config::Config::builder()
        .tls_config(
            ureq::tls::TlsConfig::builder()
                .provider(ureq::tls::TlsProvider::NativeTls)
                .build(),
        )
        .timeout_global(Some(Duration::from_secs(120)))
        .user_agent(format!("CommitWatch/{CURRENT_VERSION}"))
        .build();
    ureq::Agent::new_with_config(config)
}

pub fn fetch_manifest(endpoint: &str) -> Result<Manifest> {
    let text = if let Some(path) = endpoint.strip_prefix("file://") {
        std::fs::read_to_string(path).with_context(|| format!("read {path}"))?
    } else {
        agent()
            .get(endpoint)
            .call()
            .with_context(|| format!("GET {endpoint}"))?
            .body_mut()
            .read_to_string()
            .context("read latest.json")?
    };
    serde_json::from_str(&text).context("parse latest.json")
}

pub fn is_newer(candidate: &str, current: &str) -> bool {
    match (
        semver::Version::parse(candidate.trim_start_matches('v')),
        semver::Version::parse(current.trim_start_matches('v')),
    ) {
        (Ok(c), Ok(cur)) => c > cur,
        _ => false,
    }
}

/// The staged update, if its file still exists and is newer than this build.
pub fn staged() -> Option<Staged> {
    let path = staged_path().ok()?;
    let text = std::fs::read_to_string(path).ok()?;
    let s: Staged = serde_json::from_str(&text).ok()?;
    (s.path.exists() && is_newer(&s.version, CURRENT_VERSION)).then_some(s)
}

fn clear_staged() {
    if let Ok(p) = staged_path() {
        let _ = std::fs::remove_file(p);
    }
}

/// Fetches the manifest and, when a newer version exists, downloads and
/// verifies it. Returns the staged update without applying it.
pub fn check_and_stage(endpoint: &str) -> Result<Outcome> {
    let manifest = fetch_manifest(endpoint)?;
    if !is_newer(&manifest.version, CURRENT_VERSION) {
        clear_staged();
        return Ok(Outcome::UpToDate);
    }
    if let Some(s) = staged()
        && s.version == manifest.version.trim_start_matches('v')
    {
        return Ok(Outcome::Staged(s));
    }
    let platform = manifest
        .platforms
        .get(PLATFORM)
        .ok_or_else(|| anyhow!("latest.json has no {PLATFORM} entry"))?;
    let data = download(&platform.url)?;
    verify(&data, &platform.signature)?;

    let version = manifest.version.trim_start_matches('v').to_string();
    let dir = updates_dir()?;
    let final_path = dir.join(format!("commitwatch-{version}.exe"));
    let part = dir.join(format!("commitwatch-{version}.exe.part"));
    std::fs::write(&part, &data).with_context(|| format!("write {}", part.display()))?;
    let _ = std::fs::remove_file(&final_path);
    std::fs::rename(&part, &final_path).context("rename downloaded exe")?;

    let staged = Staged {
        version,
        notes: manifest.notes,
        path: final_path,
    };
    std::fs::write(staged_path()?, serde_json::to_string_pretty(&staged)?)?;
    Ok(Outcome::Staged(staged))
}

fn download(url: &str) -> Result<Vec<u8>> {
    if let Some(path) = url.strip_prefix("file://") {
        return std::fs::read(path).with_context(|| format!("read {path}"));
    }
    let mut resp = agent()
        .get(url)
        .call()
        .with_context(|| format!("GET {url}"))?;
    let data = resp
        .body_mut()
        .with_config()
        .limit(MAX_DOWNLOAD)
        .read_to_vec()
        .context("download body")?;
    if data.is_empty() {
        bail!("downloaded file is empty");
    }
    Ok(data)
}

/// `signature` is base64 of the minisign signature file text (Tauri format).
pub fn verify(data: &[u8], signature_b64: &str) -> Result<()> {
    let sig_bytes = base64::engine::general_purpose::STANDARD
        .decode(signature_b64.trim())
        .context("signature is not base64")?;
    let sig_text = String::from_utf8(sig_bytes).context("signature is not text")?;
    let sig = minisign_verify::Signature::decode(&sig_text)
        .map_err(|e| anyhow!("signature decode: {e}"))?;
    let pk = minisign_verify::PublicKey::decode(PUBLIC_KEY.trim())
        .map_err(|e| anyhow!("public key decode: {e}"))?;
    pk.verify(data, &sig, true)
        .map_err(|e| anyhow!("signature verification failed: {e}"))
}

/// Replaces the running exe with the staged one and starts it. The caller
/// must exit right after this returns. The new process receives
/// `--after-update <pid>` so it can wait for this one to finish and clean up.
pub fn apply(staged: &Staged) -> Result<()> {
    let exe = std::env::current_exe().context("current_exe")?;
    let data = std::fs::read(&staged.path).context("read staged exe")?;
    // Re-verify against the manifest is not possible offline; the file was
    // verified when staged and lives in the user's profile. Guard at least
    // against an empty or truncated file.
    if data.len() < 1024 {
        bail!("staged exe looks truncated");
    }
    let old = exe.with_extension("old.exe");
    let _ = std::fs::remove_file(&old);
    std::fs::rename(&exe, &old).context("rename running exe")?;
    if let Err(e) = std::fs::copy(&staged.path, &exe) {
        // Put the original back so the install is not left broken.
        let _ = std::fs::rename(&old, &exe);
        return Err(e).context("copy staged exe into place");
    }
    // Detach stdio so a console caller (e.g. `--apply-update` from a shell)
    // is not kept open by the long-lived child.
    std::process::Command::new(&exe)
        .arg("--after-update")
        .arg(std::process::id().to_string())
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .context("start updated exe")?;
    Ok(())
}

/// Waits up to 30 s for another process to exit (used after update and
/// elevation restarts so the single-instance mutex is free).
pub fn wait_for_pid(pid: u32) {
    use windows::Win32::Foundation::CloseHandle;
    use windows::Win32::System::Threading::{
        OpenProcess, PROCESS_SYNCHRONIZE, WaitForSingleObject,
    };
    if pid == 0 {
        return;
    }
    unsafe {
        if let Ok(h) = OpenProcess(PROCESS_SYNCHRONIZE, false, pid) {
            let _ = WaitForSingleObject(h, 30_000);
            let _ = CloseHandle(h);
        }
    }
}

/// Called by the new exe: waits for the old process to exit, then removes
/// the old exe and the staged files.
pub fn finish_after_update(old_pid: u32) {
    wait_for_pid(old_pid);
    if let Ok(exe) = std::env::current_exe() {
        let old = exe.with_extension("old.exe");
        for _ in 0..10 {
            if std::fs::remove_file(&old).is_ok() || !old.exists() {
                break;
            }
            std::thread::sleep(Duration::from_millis(300));
        }
    }
    clear_staged();
    if let Ok(dir) = updates_dir()
        && let Ok(entries) = std::fs::read_dir(dir)
    {
        for e in entries.flatten() {
            let _ = std::fs::remove_file(e.path());
        }
    }
}

/// Marks this process's stdio handles non-inheritable. `Command` passes
/// every inheritable handle to children, so without this a long-lived child
/// would keep a caller's pipe open even with `Stdio::null()`.
pub fn detach_inherited_stdio() {
    use windows::Win32::Foundation::{HANDLE_FLAG_INHERIT, HANDLE_FLAGS, SetHandleInformation};
    use windows::Win32::System::Console::{
        GetStdHandle, STD_ERROR_HANDLE, STD_INPUT_HANDLE, STD_OUTPUT_HANDLE,
    };
    for which in [STD_INPUT_HANDLE, STD_OUTPUT_HANDLE, STD_ERROR_HANDLE] {
        unsafe {
            if let Ok(h) = GetStdHandle(which)
                && !h.is_invalid()
            {
                let _ = SetHandleInformation(h, HANDLE_FLAG_INHERIT.0, HANDLE_FLAGS(0));
            }
        }
    }
}

/// Removes a leftover `.old.exe` from a previous update, if any.
pub fn cleanup_old_exe() {
    if let Ok(exe) = std::env::current_exe() {
        let old = exe.with_extension("old.exe");
        if old.exists() {
            let _ = std::fs::remove_file(old);
        }
    }
}

